import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(scriptDir, "..");
const assetsRoot = path.join(repoRoot, "resources/default-agent-assets");
const outputPath = path.join(repoRoot, "apps/desktop/src/lib/default-agent-assets.generated.ts");
const checkOnly = process.argv.includes("--check");

async function readAsset(relativePath) {
  return readFile(path.join(assetsRoot, relativePath), "utf8");
}

const [initialMemoryTemplate, memorySkillTemplate, guideCreateSkill, keyKnowledgeRaw, skillsRaw] =
  await Promise.all([
    readAsset("MEMORY.md.template"),
    readAsset("skills/memory/SKILL.md.template"),
    readAsset("skills/guide-create/SKILL.md"),
    readAsset("key-knowledge.json"),
    readAsset("skills.json"),
  ]);

const generated = `// Generated by scripts/generate-default-agent-assets.mjs. Do not edit by hand.

export const INITIAL_MEMORY_TEMPLATE = ${JSON.stringify(initialMemoryTemplate)};

export const DEFAULT_KEY_KNOWLEDGE = ${JSON.stringify(JSON.parse(keyKnowledgeRaw), null, 2)} as const;

export const MEMORY_SKILL_TEMPLATE = ${JSON.stringify(memorySkillTemplate)};

export const GUIDE_CREATE_SKILL = ${JSON.stringify(guideCreateSkill)};

export const DEFAULT_SKILL_DEFINITIONS = ${JSON.stringify(JSON.parse(skillsRaw), null, 2)} as const;
`;

if (checkOnly) {
  let current = "";
  try {
    current = await readFile(outputPath, "utf8");
  } catch {
    throw new Error(`${path.relative(repoRoot, outputPath)} does not exist; run generate:default-agent-assets`);
  }
  if (current !== generated) {
    throw new Error(`${path.relative(repoRoot, outputPath)} is stale; run generate:default-agent-assets`);
  }
} else {
  await writeFile(outputPath, generated);
}
